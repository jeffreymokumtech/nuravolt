def emit_map() -> Dict[str, Set[str]]:
    """Which methods actually CONSTRUCT a FaultAlert of each type."""
    src = RULE_BASED.read_text()
    tree = ast.parse(src)
    out: Dict[str, Set[str]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        seg = ast.get_source_segment(src, node) or ""
        for call in re.finditer(r"FaultAlert\((.*?)\)\s*[,\)]", seg, re.S):
            for ft in re.findall(r"FaultType\.([A-Z_]+)", call.group(1)):
                out.setdefault(ft, set()).add(node.name)
    return out


def signal_map() -> Dict[str, List[str]]:
    """Which telemetry columns each detector method searches for."""
    src = RULE_BASED.read_text()
    tree = ast.parse(src)
    out: Dict[str, List[str]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        seg = ast.get_source_segment(src, node) or ""
        found: Set[str] = set()
        for m in re.finditer(r"_find_column\w*\([^,]+,\s*\[(.*?)\]", seg, re.S):
            found.update(re.findall(r'"([^"]+)"', m.group(1)))
        out[node.name] = sorted(found)
    return out


