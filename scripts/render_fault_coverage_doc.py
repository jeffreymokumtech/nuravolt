def _firing_summary() -> str:
    """One sentence of live numbers from the firing-rate artifact, never hand-typed."""
    art = REPO / "public" / "data" / "validation" / "pv" / "rule_firing_rates_real_plants.json"
    if not art.exists():
        return "The artifact is not present in this checkout."
    d = json.loads(art.read_text())
    imp = d.get("implausible_rules") or []
    pr = d.get("peer_rewrite") or {}
    bits = []
    if pr.get("alerts_per_mw_month_after") is not None:
        bits.append(
            f"Fleet volume is {pr['alerts_per_mw_month_after']} alerts per MW-month, from "
            f"{pr['alerts_per_mw_month_before']} before the peer-relative rewrite."
        )
    bits.append(
        f"{len(imp)} rule(s) still fire above their bound"
        + (f": {', '.join('`' + r + '`' for r in imp)}." if imp else ".")
    )
    return " ".join(bits)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    body = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != body:
            print(f"{OUT} is stale; run scripts/render_fault_coverage_doc.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(body)
    print(f"wrote {OUT} ({len(body):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
