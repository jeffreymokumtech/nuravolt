"""
BESS Fault Detector

Combines reactive warranty violation detection with predictive RUL models to
produce a unified, frontend-ready fault list for each BESS asset.

Reactive faults are sourced from WarrantyViolationDetector and mapped into
the same output schema as PV faults.  Predictive faults are generated by the
five BESS RUL models and include days-to-fault, confidence, and estimated
revenue impact.

Usage:
    from nuravolt.fault import BessFaultDetector

    detector = BessFaultDetector(electricity_price_eur_kwh=0.12)

    # asset_data: dict with keys described in _extract_history_df() docstrings
    # warranty_terms: dict matching WarrantyTermsConfig fields
    reactive  = detector.detect_reactive(asset_data)
    predictive = detector.predict_faults(asset_data, warranty_terms)

    all_faults = reactive + predictive
"""

